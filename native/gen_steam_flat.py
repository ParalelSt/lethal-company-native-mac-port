#!/usr/bin/env python3
"""Generate SDK-1.49 flat API wrappers (vtable calls through the 1.49 headers) + interface accessors.
Usage: gen_steam_flat.py <steam_sdk dir> <out.cpp>"""
import json, re, sys, os, glob
sdk, out = sys.argv[1], sys.argv[2]
j = json.load(open(os.path.join(sdk, "steam_api.json")))
flat2method = {}
for it in j["interfaces"] + j.get("structs", []):
    for m in it.get("methods", []):
        if "methodname_flat" in m:
            flat2method[m["methodname_flat"]] = m["methodname"]
# interface version strings from headers
versions = {}
for h in glob.glob(os.path.join(sdk, "*.h")):
    for m in re.finditer(r'#define\s+(\w+)\s+"([A-Za-z_]+\d+)"', open(h, errors="ignore").read()):
        versions[m.group(2)] = m.group(1)
def norm(v):
    s = v.upper().replace("_INTERFACE_VERSION", "").replace("_INTERFACE_V", "")
    s = re.sub(r"\d+$", "", s); s = s.replace("STEAM", "", 1).replace("_", "")
    return s
def find_version(x, num):
    cands = [v for v in versions if v.endswith(num) and norm(v) == x.upper()]
    return cands[0] if cands else None
decl = re.compile(r'^S_API\s+(.+?)\s*\b(SteamAPI_\w+|SteamGameServer_\w+)\s*\(\s*(.*?)\s*\)\s*;', re.M)
lines = ['// GENERATED by gen_steam_flat.py from the Steamworks SDK 1.49 headers (Facepunch 2.3.2 snapshot).',
         '#include <new>', '#include "steam_api.h"', '#include "steam_gameserver.h"', '#include "steamdatagram_tickets.h"',
         'struct SteamTVRegion_t; typedef int ESteamTVRegionBehavior;', '#include "steam_api_flat.h"',
         'extern "C" void *SteamInternal_FindOrCreateUserInterface(HSteamUser, const char *);',
         'extern "C" void *SteamInternal_FindOrCreateGameServerInterface(HSteamUser, const char *);', '']
n_flat = n_acc = 0; skipped = []
for m in decl.finditer(open(os.path.join(sdk, "steam_api_flat.h")).read()):
    ret, name, params = m.group(1).strip(), m.group(2), m.group(3)
    if "ISteamTV" in name or "XboxPairwiseID" in name or name == "SteamAPI_SteamTV_v001": skipped.append(name); continue
    acc = re.match(r'SteamAPI_(Steam\w+?)_v(\d+)$', name)
    if acc and not params:
        x, num = acc.group(1), acc.group(2)
        gs = x.startswith("SteamGameServer")
        key = x[len("Steam"):]
        ver = find_version(key, num)
        if not ver and gs: ver = find_version(key[len("GameServer"):], num)
        if not ver: skipped.append(name); continue
        fn = "SteamInternal_FindOrCreateGameServerInterface(SteamGameServer_GetHSteamUser(), " if gs else "SteamInternal_FindOrCreateUserInterface(SteamAPI_GetHSteamUser(), "
        lines.append(f'{ret} {name}() {{ return ({ret}){fn}"{ver}"); }}'); n_acc += 1; continue
    plist = [p.strip() for p in params.split(",")] if params else []
    if not plist or "self" not in plist[0]: skipped.append(name); continue
    selftype = plist[0].rsplit("self", 1)[0].strip()           # e.g. "ISteamUser*" or "SteamNetworkingIdentity*"
    cls = selftype.replace("*", "").replace("const", "").strip()
    method = flat2method.get(name)
    if not method:
        if name.startswith("SteamAPI_" + cls + "_"): method = name[len("SteamAPI_" + cls + "_"):]
        else: skipped.append(name); continue
    args = []
    for p in plist[1:]:
        pm = re.match(r'(.+?)\s*([A-Za-z_]\w*)$', p)
        if not pm: skipped.append(name); break
        t, a = pm.group(1).strip(), pm.group(2)
        if t.endswith("uint64_steamid"): args.append(f"CSteamID({a})")
        elif t.endswith("uint64_gameid"): args.append(f"CGameID({a})")
        else: args.append(a)
    else:
        if method == "Construct":
            body = f"new (self) {cls}();"
        else:
            call = f"self->{method}({', '.join(args)})"
            if ret == "uint64_steamid" or ret == "uint64_gameid": body = f"return {call}.ConvertToUint64();"
            elif ret == "void": body = f"{call};"
            else: body = f"return ({ret}){call};"
        lines.append(f'{ret} {name}({params}) {{ {body} }}'); n_flat += 1
open(out, "w").write("\n".join(lines) + "\n")
print(f"flat wrappers: {n_flat}, accessors: {n_acc}, skipped: {len(skipped)}"); print(" skipped:", " ".join(skipped[:30]))
